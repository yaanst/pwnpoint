/**
 * Keyboard model of a WAI-ARIA radio group: arrows move (and wrap), Home/End jump.
 * Returns the new index, or null when the key is not handled.
 */
export function nextRadioIndex(key: string, current: number, count: number): number | null {
  switch (key) {
    case 'ArrowRight':
    case 'ArrowDown':
      return (current + 1) % count;
    case 'ArrowLeft':
    case 'ArrowUp':
      return (current - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
